"""Export workflow contracts as deterministic JSON Schema."""

import json
from typing import Union

from pydantic import TypeAdapter

from galaius_core import (
    ModelCriteriaCatalog,
    ModelEligibility,
    WorkflowBlockAvailability,
    AdminWorkspaceSummary,
    DelegatedAgentTool,
    AgentCatalogSnapshot,
    AgentGraph,
    AgentGraphUpdate,
    AgentRevision,
    BudgetPolicy,
    ConnectionResource,
    ConnectionSecretUpdate,
    Conversation,
    ConversationActivity,
    ConversationCreateRequest,
    ConversationAppendRequest,
    ConversationPage,
    HttpAgentTool,
    SubscriptionConfiguration,
    TriggerBinding,
    TriggerConfigurationUpdate,
    TriggerCreate,
    TriggerDefinition,
    TriggerDispatch,
    TriggerEnableUpdate,
    TriggerInputMapping,
    TriggerInvocation,
    TriggerScheduleState,
    WebhookCredentialCreated,
    WebhookCredentialSummary,
    WorkspaceApiKeyCreate,
    WorkspaceApiKeyCreated,
    WorkspaceApiKeySummary,
    WorkflowEvent,
    WorkflowAgentActivity,
    WorkflowCapabilityActivity,
    WorkflowRevision,
    WorkflowValueSummary,
    NodeLibraryDefinition,
    NodeLibraryEntry,
    WorkflowRun,
    UsageSummary,
)


def main() -> None:
    contracts = Union[
        ModelCriteriaCatalog,
        ModelEligibility,
        WorkflowBlockAvailability,
        WorkspaceApiKeyCreate,
        WorkspaceApiKeyCreated,
        WorkspaceApiKeySummary,
        TriggerBinding,
        TriggerConfigurationUpdate,
        TriggerCreate,
        TriggerDefinition,
        TriggerDispatch,
        TriggerEnableUpdate,
        TriggerInputMapping,
        TriggerInvocation,
        TriggerScheduleState,
        WebhookCredentialCreated,
        WebhookCredentialSummary,
        SubscriptionConfiguration,
        AdminWorkspaceSummary,
        WorkflowAgentActivity,
        WorkflowCapabilityActivity,
        WorkflowValueSummary,
        HttpAgentTool,
        DelegatedAgentTool,
        WorkflowRevision,
        ConnectionResource,
        ConnectionSecretUpdate,
        AgentCatalogSnapshot,
        AgentGraph,
        AgentGraphUpdate,
        AgentRevision,
        ConversationCreateRequest,
        ConversationAppendRequest,
        ConversationPage,
        Conversation,
        ConversationActivity,
        BudgetPolicy,
        UsageSummary,
        WorkflowRun,
        WorkflowEvent,
        NodeLibraryDefinition,
        NodeLibraryEntry,
    ]
    print(json.dumps(TypeAdapter(contracts).json_schema(), indent=2, sort_keys=True))


if __name__ == "__main__":
    main()
