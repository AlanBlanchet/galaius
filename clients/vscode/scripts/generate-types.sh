#!/usr/bin/env bash
# Generate TypeScript types from galaius/api_types.py.
# Output is checked in (clients/vscode/src/generated/types.ts) so the
# extension can build without invoking Python.
set -e

HERE="$(cd "$(dirname "$0")" && pwd)"
EXT_DIR="$(dirname "$HERE")"
REPO_DIR="$(dirname "$(dirname "$EXT_DIR")")"
OUT="$EXT_DIR/src/generated/types.ts"

mkdir -p "$(dirname "$OUT")"

cd "$REPO_DIR"

# pydantic2ts shells out to `json2ts`; ensure the local node_modules bin is on PATH.
export PATH="$EXT_DIR/node_modules/.bin:$PATH"
# Schema generation imports the model catalog. Keep that build step on bundled data: compiling
# the extension must never refresh LiteLLM pricing or probe a configured Ollama account.
export LITELLM_LOCAL_MODEL_COST_MAP="True"
export OLLAMA_DISCOVERY="0"

# Prefer a sibling galaius-core checkout while developing both. A checkout without
# that sibling must resolve the released dependency instead of treating a missing local path as
# the package source.
CORE_SOURCE_DIR="$REPO_DIR/../galaius-core"
UV_RUN=(uv run --directory "$REPO_DIR")
if [ -f "$CORE_SOURCE_DIR/pyproject.toml" ]; then
    UV_RUN+=(--with-editable "$CORE_SOURCE_DIR")
fi

if ! "${UV_RUN[@]}" python -c "import pydantic2ts" >/dev/null 2>&1; then
    echo "[generate-types] pydantic-to-typescript not installed; skipping." >&2
    exit 0
fi

# Writes only inside this checkout (the hook runs it on every commit here). galaius-core's checked-in schemas
# are refreshed on purpose by `core-schemas.sh <core checkout>`, committed in galaius-core.
"${UV_RUN[@]}" pydantic2ts \
    --module galaius.api_types \
    --output "$OUT"
"${UV_RUN[@]}" pydantic2ts \
    --module galaius_core.prompts \
    --output "$EXT_DIR/src/generated/promptContracts.ts"
SCHEMA_OUT="$EXT_DIR/out/generated/conversation-schemas.json"
mkdir -p "$(dirname "$SCHEMA_OUT")"
"${UV_RUN[@]}" python "$HERE/schema/runtime.py" > "$SCHEMA_OUT"
node "$HERE/schema/runtime.js" "$SCHEMA_OUT"

# Prepend header if pydantic2ts didn't add one.
if ! head -1 "$OUT" | grep -q "generated"; then
    HEADER="// AUTO-GENERATED by clients/vscode/scripts/generate-types.sh.\n// Source: galaius/api_types.py. Do not edit by hand.\n"
    printf "%b%s" "$HEADER" "$(cat "$OUT")" > "$OUT"
fi

echo "[generate-types] wrote $OUT" >&2
